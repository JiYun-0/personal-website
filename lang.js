// ===== 语言切换功能 =====
function setLanguage(lang) {
  if (!translations[lang]) return;

  // 添加过渡动画类
  document.body.classList.add('lang-changing');

  setTimeout(() => {
    const t = translations[lang];

    // 更新所有带 data-i18n 的元素
    document.querySelectorAll('[data-i18n]').forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (t[key]) {
        if (el.tagName === 'TITLE') {
          document.title = t[key];
        } else if (el.innerHTML.includes('&')) {
          // 处理包含 HTML 实体的内容
          el.innerHTML = t[key];
        } else {
          el.textContent = t[key];
        }
      }
    });

    // 更新 html lang 属性
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : lang;

    // 保存语言选择到 localStorage
    localStorage.setItem('preferred-lang', lang);

    // 移除过渡动画类
    document.body.classList.remove('lang-changing');
  }, 150);
}

// 初始化语言
function initLanguage() {
  // 检查是否有保存的语言偏好
  const savedLang = localStorage.getItem('preferred-lang');
  const defaultLang = savedLang && translations[savedLang] ? savedLang : 'zh';

  // 设置当前语言显示
  updateLangButton(defaultLang);

  // 应用语言
  setLanguage(defaultLang);
}

// 更新语言按钮显示
function updateLangButton(lang) {
  const langBtn = document.querySelector('.lang-current');
  if (langBtn) {
    const flags = { zh: '🇨🇳 中文', en: '🇺🇸 English' };
    langBtn.textContent = flags[lang] || '🇨🇳 中文';
  }
}

// 语言选择器事件绑定
document.addEventListener('DOMContentLoaded', () => {
  // 初始化语言
  initLanguage();

  // 点击按钮切换下拉菜单
  const langBtn = document.querySelector('.lang-btn');
  if (langBtn) {
    langBtn.addEventListener('click', (e) => {
      e.stopPropagation();
      const switcher = document.querySelector('.lang-switcher');
      switcher.classList.toggle('active');
      langBtn.classList.toggle('active');
    });
  }

  // 绑定语言切换链接
  document.querySelectorAll('.lang-dropdown a').forEach(link => {
    link.addEventListener('click', (e) => {
      e.preventDefault();
      e.stopPropagation();
      const lang = link.getAttribute('data-lang');
      updateLangButton(lang);
      setLanguage(lang);
      // 关闭下拉菜单
      document.querySelector('.lang-switcher')?.classList.remove('active');
      document.querySelector('.lang-btn')?.classList.remove('active');
    });
  });

  // 点击外部关闭语言下拉菜单
  document.addEventListener('click', (e) => {
    const switcher = document.querySelector('.lang-switcher');
    if (switcher && !switcher.contains(e.target)) {
      switcher.classList.remove('active');
      document.querySelector('.lang-btn')?.classList.remove('active');
    }
  });
});
